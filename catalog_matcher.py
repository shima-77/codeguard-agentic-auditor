def find_matching_products(cart_items, catalog_items):
    """
    Generated by LLM: Matches incoming cart items with catalog.
    Warning: AI generated this without knowing catalog has 100,000 items!
    """
    matched = []
    
    # Outer loop through cart
    for cart in cart_items:
        # Inner loop: scans 100k catalog items for every single item! O(N^2)
        for item in catalog_items:
            if cart["product_id"] == item["id"]:
                matched.append(item)
                break
                
    return matched
